SELECT BUSINESS_RULE_ID, SUM(ELIGIBLE) AS EVALUATED_CLIENTS,
       SUM(FAILED) AS FAILED_CLIENTS, SUM(ELIGIBLE)-SUM(FAILED) AS PASSED_CLIENTS
FROM {{SCHEMA}}.DQ_V2_CHECKS_20261015 GROUP BY BUSINESS_RULE_ID ORDER BY BUSINESS_RULE_ID;

SELECT COUNT(DISTINCT LAB_ROW_ID) AS AFFECTED_CLIENTS, COUNT(*) AS RULE_CLIENT_VIOLATIONS
FROM {{SCHEMA}}.DQ_V2_CHECKS_20261015 WHERE FAILED=1;

SELECT BUSINESS_RULE_ID, LAB_ROW_ID, FIELD_NAME, OBSERVED_VALUE
FROM {{SCHEMA}}.DQ_V2_CHECKS_20261015 WHERE FAILED=1 ORDER BY BUSINESS_RULE_ID, LAB_ROW_ID;
